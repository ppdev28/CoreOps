const attributes = (source) =>
  Object.fromEntries(
    [...source.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]),
  );
const color = (value) =>
  !value || value === "none"
    ? "@android:color/transparent"
    : value === "currentColor"
      ? "#F2F2F2"
      : value;

function geometry(tag, a) {
  const x = +(a.x ?? 0),
    y = +(a.y ?? 0);
  if (tag === "path") return a.d;
  if (tag === "line") return `M${a.x1},${a.y1}L${a.x2},${a.y2}`;
  if (tag === "polyline" || tag === "polygon") {
    const points = a.points.trim().split(/[\s,]+/);
    return `M${points[0]},${points[1]}${points.slice(2).reduce((s, n, i) => s + (i % 2 ? "," : "L") + n, "")}${tag === "polygon" ? "Z" : ""}`;
  }
  if (tag === "circle")
    return `M${+a.cx - +a.r},${a.cy}a${a.r},${a.r} 0,1 0,${2 * +a.r},0a${a.r},${a.r} 0,1 0,${-2 * +a.r},0`;
  if (tag === "rect") {
    const w = +a.width,
      h = +a.height;
    const rx = Math.min(+(a.rx ?? a.ry ?? 0), w / 2);
    const ry = Math.min(+(a.ry ?? a.rx ?? 0), h / 2);
    if (!rx || !ry) return `M${x},${y}h${w}v${h}h${-w}Z`;
    return `M${x + rx},${y}h${w - 2 * rx}a${rx},${ry} 0,0 1,${rx},${ry}v${h - 2 * ry}a${rx},${ry} 0,0 1,${-rx},${ry}h${2 * rx - w}a${rx},${ry} 0,0 1,${-rx},${-ry}v${2 * ry - h}a${rx},${ry} 0,0 1,${rx},${-ry}Z`;
  }
  throw new Error(`Unsupported SVG geometry: ${tag}`);
}

function paths(svg) {
  const stack = [{ fill: "none" }];
  const result = [];
  for (const match of svg.matchAll(
    /<(\/?)(svg|g|path|rect|circle|line|polyline|polygon)\b([^>]*)>/g,
  )) {
    const [, closing, tag, source] = match;
    if (closing) {
      if (tag === "svg" || tag === "g") stack.pop();
      continue;
    }
    const a = { ...stack.at(-1), ...attributes(source) };
    if (tag === "svg" || tag === "g") {
      stack.push(a);
      continue;
    }
    const props = [`android:fillColor="${color(a.fill)}"`];
    if (a.stroke && a.stroke !== "none")
      props.push(
        `android:strokeColor="${color(a.stroke)}"`,
        `android:strokeWidth="${a["stroke-width"] ?? 1}"`,
        `android:strokeLineCap="${a["stroke-linecap"] ?? "round"}"`,
        `android:strokeLineJoin="${a["stroke-linejoin"] ?? "round"}"`,
      );
    result.push(
      `    <path ${props.join(" ")}\n        android:pathData="${geometry(tag, a)}" />`,
    );
  }
  return result.join("\n");
}
