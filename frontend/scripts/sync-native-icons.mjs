const browser = await chromium.launch({
  ...(process.env.COREOPS_CHROMIUM_PATH
    ? { executablePath: process.env.COREOPS_CHROMIUM_PATH }
    : {}),
});
try {
  const page = await browser.newPage();
  async function raster(size, format, svg = favicon) {
    const data = await page.evaluate(
      async ({ svg, size, format }) => {
        const image = new Image();
        image.src = `data:image/svg+xml,${encodeURIComponent(svg)}`;
        await image.decode();
        const canvas = document.createElement("canvas");
        canvas.width = canvas.height = size;
        const ctx = canvas.getContext("2d");
        ctx.drawImage(image, 0, 0, size, size);
        return canvas.toDataURL(`image/${format}`, 1).split(",")[1];
      },
      { svg, size, format },
    );
    return Buffer.from(data, "base64");
  }
  for (const [density, size] of Object.entries({
    mdpi: 48,
    hdpi: 72,
    xhdpi: 96,
    xxhdpi: 144,
    xxxhdpi: 192,
  })) {
    for (const name of ["ic_launcher", "ic_launcher_round"]) {
      await writeFile(
        resolve(res, `mipmap-${density}/${name}.webp`),
        await raster(
          size,
          "webp",
          name.endsWith("_round") ? roundFavicon : favicon,
        ),
      );
    }
  }
  await save(
    "android/app/src/main/res/drawable/server_icon.png",
    await raster(256, "png"),
  );
  // Browser screenshots encode opaque RGB PNGs; canvas PNGs retain an alpha
  // channel even with alpha:false, which is unsuitable for an iOS AppIcon.
  await page.setViewportSize({ width: 1024, height: 1024 });
  await page.setContent(
    `<style>body{margin:0;background:#171717}svg{display:block;width:1024px;height:1024px}</style>${favicon}`,
  );
  const iosIcon = await page.screenshot({ type: "png", omitBackground: false });
  if (iosIcon[25] !== 2)
    throw new Error("iOS AppIcon must be an RGB PNG without alpha");
  await save(
    "ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png",
    iosIcon,
  );
} finally {
  await browser.close();
}
